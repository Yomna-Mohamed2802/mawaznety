// ─── Smart Matching Engine ──────────────────────────────

function expandSynonyms(words) {
  const expanded = new Set(words);
  for (const [base, syns] of Object.entries(SYNONYMS)) {
    for (const w of words) {
      if (syns.some((s) => w.includes(s) || s.includes(w))) {
        expanded.add(base);
        syns.forEach((s) => expanded.add(s));
      }
    }
  }
  return [...expanded];
}

function tokenize(text) {
  const norm = normalize(text);
  const words = norm.split(" ").filter(Boolean);
  return expandSynonyms(words);
}

/**
 * Find the best matching response for a user query.
 *
 * @param {string} query - User's input text
 * @returns {{ reply: string, confidence: number }}
 */
export function getChatResponse(query) {
  const norm = normalize(query);
  if (!norm) {
    return { reply: "اكتب سؤالك عن الموازنة وأنا جاهز اجاوبك!", confidence: 1 };
  }

  const queryTokens = tokenize(query);
  let bestQA = null;
  let bestScore = 0;

  for (const entry of QA) {
    let score = 0;
    for (const keyword of entry.q) {
      const kwNorm = normalize(keyword);

      // Exact match
      if (norm.includes(kwNorm)) {
        score += kwNorm.length * 3;
        continue;
      }

      // Token overlap
      const kwTokens = kwNorm.split(" ");
      for (const t of queryTokens) {
        for (const kt of kwTokens) {
          if (t === kt) score += 3;
          else if (t.includes(kt) || kt.includes(t)) score += 2;
          else if (levenshtein(t, kt) <= 1 && t.length > 3) score += 1;
        }
      }
    }
    if (score > bestScore) {
      bestScore = score;
      bestQA = entry;
    }
  }

  if (bestQA && bestScore >= 3) {
    return { reply: bestQA.a, confidence: Math.min(bestScore / 10, 1) };
  }

  // Try to detect the topic and give a helpful fallback
  if (norm.includes("كم") || norm.includes("ايه هو") || norm.includes("ايه هي")) {
    return {
      reply: "ممكن توضح السؤال أكتر؟ جرّب تسأل:\n• كم مصروفات التعليم؟\n• ايه هو العجز؟\n• كم الدين؟",
      confidence: 0.3,
    };
  }

  return {
    reply: "مش فاهم السؤال ده. جرّب تسأل عن:\n• الموازنة والعجز\n• الدين والفوائد\n• التعليم والصحة\n• الاستثمارات وحياة كريمة\n• 100 جنيه بتروح فين",
    confidence: 0,
  };
}

// ─── Levenshtein Distance (fuzzy matching) ──────────────

function levenshtein(a, b) {
  if (a.length === 0) return b.length;
  if (b.length === 0) return a.length;
  const matrix = [];
  for (let i = 0; i <= b.length; i++) matrix[i] = [i];
  for (let j = 0; j <= a.length; j++) matrix[0][j] = j;
  for (let i = 1; i <= b.length; i++) {
    for (let j = 1; j <= a.length; j++) {
      const cost = b[i - 1] === a[j - 1] ? 0 : 1;
      matrix[i][j] = Math.min(
        matrix[i - 1][j] + 1,
        matrix[i][j - 1] + 1,
        matrix[i - 1][j - 1] + cost
      );
    }
  }
  return matrix[b.length][a.length];
}

