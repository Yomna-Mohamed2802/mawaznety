/**
 * Find the best matching response for a user query.
 *
 * @param {string} query - User's input text
 * @returns {{ reply: string, category: string, source?: string }}
 */
export function getChatResponse(query) {
  const normalized = query
    .toLowerCase()
    .replace(/[؟?!,.،]/g, "")
    .trim();

  if (!normalized) {
    return {
      reply: "اكتب سؤالك عن الموازنة وأنا جاهز اجاوبك!",
      category: "empty",
    };
  }

  let bestMatch = null;
  let bestScore = 0;

  for (const entry of responses) {
    let score = 0;
    for (const kw of entry.keywords) {
      const kwNorm = kw.toLowerCase().replace(/[؟?!,.،]/g, "").trim();
      if (normalized.includes(kwNorm) || kwNorm.includes(normalized)) {
        score += kwNorm.length;
      }
    }
    if (score > bestScore) {
      bestScore = score;
      bestMatch = entry;
    }
  }

  if (bestMatch && bestScore > 0) {
    return {
      reply: bestMatch.reply,
      category: bestMatch.category,
      source: bestMatch.source,
    };
  }

  return {
    reply: "مش فاهم السؤال ده. جرّب تسأل عن: الموازنة، العجز، الدين، التعليم، الصحة، الاستثمارات، أو 100 جنيه.",
    category: "unknown",
  };
}

