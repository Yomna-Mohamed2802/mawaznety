// ─── Normalization ──────────────────────────────────────

function normalize(text) {
  return text
    .toLowerCase()
    .replace(/[؟?!,.،:：؛\n\r]/g, "")
    .replace(/[\u0610-\u061A]/g, "")   // tashkeel
    .replace(/[\u064B-\u065F]/g, "")   // tashkeel
    .replace(/[\u0670]/g, "")          // dagger alif
    .replace(/\s+/g, " ")
    .trim();
}

